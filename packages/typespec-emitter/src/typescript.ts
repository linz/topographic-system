import { emitFile, getDirectoryPath, getDoc, joinPaths } from '@typespec/compiler';
import type { EmitContext, Enum, Model, Program, Type, Union } from '@typespec/compiler';

import { planEmission, unitOutputDir } from './plan.ts';
import { collectOwnTypes, collectTypes, toPascalCase } from './utils.ts';

function formatPropName(name: string): string {
  return /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}

/** Formats a doc comment as JSDoc, indented by `indent`. Collapses to a single line when short enough. */
function toComment(doc: string | undefined, indent = ''): string {
  if (!doc) return '';
  const lines = doc.trim().split('\n');
  if (lines.length === 1) {
    return `${indent}/** ${lines[0]} */\n`;
  }
  return `${indent}/**\n${lines.map((line) => `${indent} * ${line}`).join('\n')}\n${indent} */\n`;
}

export function generateTypeScriptCode(
  program: Program,
  models: Map<string, Model>,
  enums: Map<string, Enum>,
  unions: Map<string, Union>,
): string {
  function getJSDocComment(type: Type): string {
    return toComment(getDoc(program, type), '  ');
  }

  function getTsType(type: Type): string {
    switch (type.kind) {
      case 'Intrinsic':
        if (type.name === 'void') return 'void';
        if (type.name === 'never') return 'never';
        if (type.name === 'null') return 'null';
        if (type.name === 'unknown') return 'unknown';
        return 'any';
      case 'String':
        return JSON.stringify(type.value);
      case 'Number':
        return String(type.value);
      case 'Boolean':
        return String(type.value);
      case 'Scalar':
        switch (type.name) {
          case 'string':
            return 'string';
          case 'boolean':
            return 'boolean';
          case 'int32':
          case 'int64':
          case 'int16':
          case 'int8':
          case 'uint32':
          case 'uint16':
          case 'uint8':
          case 'float32':
          case 'float64':
          case 'numeric':
          case 'integer':
          case 'safeint':
          case 'float':
          case 'decimal':
          case 'decimal128':
            return 'number';
          case 'utcDateTime':
          case 'offsetDateTime':
          case 'plainDate':
          case 'plainTime':
          case 'duration':
          case 'url':
            return 'string';
          default:
            return type.name ? toPascalCase(type.name) : 'any';
        }
      case 'Enum':
        return toPascalCase(type.name);
      case 'Union':
        if (type.name) {
          return toPascalCase(type.name);
        }
        const unionTypes = Array.from(type.variants.values()).map((v) => getTsType(v.type));
        const uniqueUnionTypes = Array.from(new Set(unionTypes));
        return uniqueUnionTypes.join(' | ');
      case 'Tuple':
        return `[${type.values.map(getTsType).join(', ')}]`;
      case 'Model':
        if (type.name === 'Array') {
          if (type.indexer) {
            return `${getTsType(type.indexer.value)}[]`;
          }
          return 'any[]';
        }
        if (type.name === 'Record') {
          if (type.indexer) {
            return `Record<${getTsType(type.indexer.key)}, ${getTsType(type.indexer.value)}>`;
          }
          return 'Record<string, any>';
        }
        if (type.name && type.name !== 'object') {
          return toPascalCase(type.name);
        }
        if (type.properties.size === 0) {
          return 'Record<string, unknown>';
        }
        const props: string[] = [];
        for (const prop of type.properties.values()) {
          props.push(`${formatPropName(prop.name)}${prop.optional ? '?' : ''}: ${getTsType(prop.type)}`);
        }
        return `{ ${props.join('; ')} }`;
      case 'ModelProperty':
        return getTsType(type.type);
      case 'EnumMember':
        return type.value !== undefined ? JSON.stringify(type.value) : JSON.stringify(type.name);
      case 'UnionVariant':
        return getTsType(type.type);
      default:
        return 'any';
    }
  }

  let code = `/**\n * This file was automatically generated by the TypeSpec TypeScript emitter.\n * Do not edit this file manually.\n */\n\n`;

  // Generate Enums as Type Aliases (erasable syntax)
  const sortedEnums = Array.from(enums.values()).sort((a, b) => a.name.localeCompare(b.name));
  for (const e of sortedEnums) {
    const doc = getDoc(program, e);
    const memberValues = Array.from(e.members.values()).map((member) =>
      member.value !== undefined ? JSON.stringify(member.value) : JSON.stringify(member.name),
    );
    code += `${toComment(doc)}export type ${toPascalCase(e.name)} = ${memberValues.join(' | ')};\n\n`;
  }

  // Generate Unions
  const sortedUnions = Array.from(unions.values()).sort((a, b) => (a.name ?? '').localeCompare(b.name ?? ''));
  for (const u of sortedUnions) {
    const doc = getDoc(program, u);
    const unionTypes = Array.from(u.variants.values()).map((v) => getTsType(v.type));
    const uniqueUnionTypes = Array.from(new Set(unionTypes));
    code += `${toComment(doc)}export type ${toPascalCase(u.name ?? '')} = ${uniqueUnionTypes.join(' | ')};\n\n`;
  }

  // Generate Models
  const sortedModels = Array.from(models.values()).sort((a, b) => a.name.localeCompare(b.name));
  for (const m of sortedModels) {
    const doc = getDoc(program, m);
    const extendsClause = m.baseModel?.name ? ` extends ${toPascalCase(m.baseModel.name)}` : '';
    code += `${toComment(doc)}export interface ${toPascalCase(m.name)}${extendsClause} {\n`;
    if (m.indexer) {
      const keyType = getTsType(m.indexer.key);
      const valueType = getTsType(m.indexer.value);
      code += `  [key: ${keyType}]: ${valueType};\n`;
    }
    for (const prop of m.properties.values()) {
      const propComment = getJSDocComment(prop);
      code += `${propComment}  ${formatPropName(prop.name)}${prop.optional ? '?' : ''}: ${getTsType(prop.type)};\n`;
    }
    code += '}\n\n';
  }

  return code;
}

/**
 * Emits TypeScript types, one `index.ts` per (version × product) unit — see `planEmission`. Each
 * unit combines its own namespace's types with any declared directly on the shared root at that
 * version. When `outputTarget` ends in `.ts`, its directory is used as the output root (so a
 * single flat, unversioned, product-less program still writes exactly to `outputTarget`).
 *
 * When every unit is a plain release (versioned, no product split), a top-level `index.ts` is
 * also written re-exporting every release, defaulting to the latest — there's no such "latest"
 * export generated across sibling products, since their types can share names (e.g. both
 * `NzTopo50` and `NzTopo250` may declare `airport`) and a combined `export *` would collide.
 */
export async function emitTypeScript(context: EmitContext<any>, outputTarget: string): Promise<void> {
  const { program } = context;
  const units = planEmission(program);
  const outputDir = outputTarget.endsWith('.ts') ? getDirectoryPath(outputTarget) : outputTarget;

  for (const unit of units) {
    const models = new Map<string, Model>();
    const enums = new Map<string, Enum>();
    const unions = new Map<string, Union>();

    if (unit.sharedNs) collectOwnTypes(unit.sharedNs, models, enums, unions);
    if (unit.ownOnly) {
      collectOwnTypes(unit.ns, models, enums, unions);
    } else {
      collectTypes(unit.ns, models, enums, unions);
    }

    const code = generateTypeScriptCode(program, models, enums, unions);
    const targetFile =
      !unit.path && outputTarget.endsWith('.ts')
        ? outputTarget
        : joinPaths(unitOutputDir(outputDir, unit.path), 'index.ts');
    await emitFile(program, { path: targetFile, content: code });
  }

  const releaseUnits = units.filter((u) => u.versionStr != null && u.productName == null && !u.ownOnly);
  const latest = releaseUnits.length === units.length ? releaseUnits.at(-1) : undefined;
  if (latest) {
    let indexCode = `/**\n * This file was automatically generated by the TypeSpec TypeScript emitter.\n * Do not edit this file manually.\n *\n * Points to the latest schema version (v${latest.versionStr}).\n */\n\n`;
    indexCode += `export * from './${latest.path}/index.ts';\n\n`;
    for (const unit of releaseUnits) {
      const identifier = `v${String(unit.versionStr).replace(/[^a-zA-Z0-9_$]/g, '_')}`;
      indexCode += `export * as ${identifier} from './${unit.path}/index.ts';\n`;
    }
    await emitFile(program, { path: joinPaths(outputDir, 'index.ts'), content: indexCode });
  }
}
